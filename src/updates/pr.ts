// "Open or update the PR": the update as a commit on the base commit, made
// through the API (GitHub signs it, no credentials touch a checkout), on
// the branch `maintenance-updates/<kind>`, and the PR opened or edited.
// When nothing is due any more, this workflow's PR is closed and its
// branch deleted; anyone else's commit on the branch leaves both alone.

import { createHash } from "node:crypto";
import { appendRunnerFile, warning } from "../lib/actions.ts";
import { Fail } from "../lib/env.ts";
import { run } from "../lib/exec.ts";
import { api as githubApi, isNotFound } from "../lib/github.ts";
import type { Api } from "../lib/github.ts";
import { HttpError } from "../lib/http.ts";
import { pushUpdate } from "./commit.ts";
import { readMeta, updateContext } from "./context.ts";
import type { Kind, Meta, UpdateContext } from "./context.ts";
import {
  readContent,
  readPaths,
  readState,
  readSummary,
  readTitle,
} from "./outcome.ts";
import type { Outcome } from "./outcome.ts";

const BOT = "github-actions[bot]";
const LABEL = "maintenance-updates";
const SOURCE_LINK =
  " · Source: [valuecodes/automation](https://github.com/valuecodes/automation)";

const label = (kind: Kind): string =>
  ({ node: "Node.js", catalog: "Dependencies" })[kind as string] ?? kind;

/** The PR title is a plain sentence; the commit follows the
 * `<type>: <subject>` convention, with the trailer `ours` checks. */
const commitMessage = (title: string, kind: Kind): string =>
  `chore: ${title.charAt(0).toLowerCase()}${title.slice(1)}\n\nMaintenance-Updates: ${kind}`;

type BodyInput = {
  ciWorkflow: string;
  dashboard: number | null;
  caller: string;
  runsUrl: string;
  date: string;
};

type Body = {
  /** The content with the notes, which the marker hashes. */
  content: string;
  body: string;
  note: string;
  marker: string;
};

/** The same footer as the dashboard issue. The hash excludes the date, so
 * an unchanged body is not re-saved. */
const body = (title: string, text: string, input: BodyInput): Body => {
  let content = text;
  content +=
    input.ciWorkflow === ""
      ? "\n\nThis PR was opened with `GITHUB_TOKEN`, so its `pull_request` workflows wait for approval: use **Approve workflows to run** in the PR, or set `ci-workflow` in the caller."
      : `\n\nCI runs through \`workflow_dispatch\` of \`${input.ciWorkflow}\`, so it starts without approval. GitHub holds this PR's \`pull_request\` runs for approval; you can leave them.`;
  if (input.dashboard !== null) {
    content += `\n\nDashboard: #${input.dashboard}`;
  }
  const note = `Generated by the \`${input.caller}\` workflow; manual edits are overwritten.`;
  const hash = createHash("sha256")
    .update(`${title}\n${content}`)
    .digest("hex");
  const marker = `<!-- maintenance-updates:${hash} -->`;
  return {
    content,
    body: `${content}\n\n---\nLast changed: ${input.date} · [Workflow runs](${input.runsUrl})${SOURCE_LINK}\n\n${note}\n${marker}\n`,
    note,
    marker,
  };
};

type Pull = {
  number: number;
  title?: string;
  body?: string | null;
  html_url?: string;
  merged_at?: string | null;
  user?: { login?: string } | null;
  head?: { repo?: { full_name?: string } | null } | null;
};

/** Unchanged means the same title, content, footer and marker, as in the
 * dashboard, so the PR's edit history shows real changes. */
const unchanged = (pr: Pull, title: string, built: Body): boolean => {
  const existing = (pr.body ?? "").replaceAll("\r", "").replace(/\n+$/, "");
  const prefix = `${built.content}\n\n---\nLast changed: `;
  const suffix = `${SOURCE_LINK}\n\n${built.note}\n${built.marker}`;
  return (
    pr.title === title &&
    existing.startsWith(prefix) &&
    existing.endsWith(suffix) &&
    existing.length >= prefix.length + suffix.length
  );
};

type Compare = {
  total_commits?: number;
  commits?: {
    author?: { login?: string } | null;
    commit?: { message?: string };
  }[];
};

/**
 * Every commit the branch adds to the base is this workflow's: the bot
 * author alone is not enough, since any workflow using `GITHUB_TOKEN`
 * commits as it, so the commit must also carry this kind's trailer. The
 * compare API returns at most 250 commits, so a longer history fails
 * closed. This guards against overwriting work, not against anyone with
 * push access, who can forge both.
 */
const ours = (compare: Compare, kind: Kind): boolean => {
  const commits = compare.commits ?? [];
  if ((compare.total_commits ?? commits.length) > commits.length) {
    return false;
  }
  return commits.every(
    (c) =>
      c.author?.login === BOT &&
      (c.commit?.message ?? "")
        .split("\n")
        .includes(`Maintenance-Updates: ${kind}`),
  );
};

/** Up to 300 lines of the unified diff of one changed file. */
const diffOf = async (out: string, path: string): Promise<string> => {
  const result = await run("diff", [
    "-u",
    "--label",
    `a/${path}`,
    "--label",
    `b/${path}`,
    `${out}/old/${path}`,
    `${out}/new/${path}`,
  ]);
  return result.stdout.split("\n").slice(0, 300).join("\n");
};

type Log = (line: string) => void;

const publish = async (
  api: Api,
  ctx: UpdateContext,
  meta: Meta,
  outcome: Outcome,
  log: Log = console.log,
): Promise<void> => {
  const { repo, kind } = ctx;
  const branch = `maintenance-updates/${kind}`;
  const owner = repo.split("/")[0] ?? "";
  // This workflow's PRs from this repo; a fork's PR on a branch of the same
  // name is not its to touch.
  const pulls = async (state: "open" | "closed"): Promise<Pull[]> =>
    (
      await api<Pull[]>(
        "GET",
        `repos/${repo}/pulls?head=${encodeURIComponent(`${owner}:${branch}`)}&state=${state}&per_page=100`,
      )
    )
      .filter((p) => p.user?.login === BOT && p.head?.repo?.full_name === repo)
      .sort((a, b) => a.number - b.number);
  const pr = (await pulls("open"))[0] ?? null;
  let tip: string | null;
  try {
    tip =
      (
        await api<{ object?: { sha?: string } }>(
          "GET",
          `repos/${repo}/git/ref/heads/${branch}`,
        )
      ).object?.sha ?? null;
  } catch (error) {
    if (!isNotFound(error)) {
      throw error;
    }
    tip = null;
  }
  const isOurs = async (sha: string): Promise<boolean> =>
    ours(
      await api<Compare>(
        "GET",
        `repos/${repo}/compare/${meta.baseSha}...${sha}`,
      ),
      kind,
    );

  if (outcome.state !== "update") {
    appendRunnerFile(
      "GITHUB_STEP_SUMMARY",
      `**${label(kind)}:** ${outcome.reason}.\n`,
    );
    if (tip !== null) {
      if (!(await isOurs(tip))) {
        warning(
          `${branch} has commits not made by this workflow; leaving it and its PR alone.`,
        );
      } else if (ctx.dryRun) {
        log(
          `Dry run: would close ${pr === null ? "" : `#${pr.number} and `}delete ${branch}.`,
        );
      } else if (pr !== null) {
        await api("POST", `repos/${repo}/issues/${pr.number}/comments`, {
          body: `Closed by the \`${ctx.caller}\` workflow: ${outcome.reason}.`,
        });
        await api("PATCH", `repos/${repo}/pulls/${pr.number}`, {
          state: "closed",
        });
        await api("DELETE", `repos/${repo}/git/refs/heads/${branch}`);
        log(`Closed #${pr.number}: ${outcome.reason}.`);
      } else {
        await api("DELETE", `repos/${repo}/git/refs/heads/${branch}`);
        log(`Deleted ${branch}, left over without a PR.`);
      }
    }
    if (outcome.state === "blocked") {
      process.exitCode = 1;
    }
    return;
  }

  const title = readTitle(ctx.out);
  const built = body(title, readContent(ctx.out), {
    ciWorkflow: ctx.ciWorkflow,
    dashboard: meta.dashboard,
    caller: ctx.caller,
    runsUrl: ctx.runsUrl,
    date: new Date().toISOString().slice(0, 10),
  });
  const summary = readSummary(ctx.out);
  appendRunnerFile(
    "GITHUB_STEP_SUMMARY",
    `## ${title}\n\n${built.content}\n${summary === null ? "" : `\n${summary}`}`,
  );
  const paths = readPaths(ctx.out);

  if (ctx.dryRun) {
    const diffs: string[] = [];
    for (const path of paths) {
      diffs.push(await diffOf(ctx.out, path));
    }
    appendRunnerFile(
      "GITHUB_STEP_SUMMARY",
      `\n<details><summary>Diff</summary>\n\n\`\`\`diff\n${diffs.join("\n")}\n\`\`\`\n\n</details>\n`,
    );
    log("Dry run: the planned PR is in the run summary; nothing was pushed.");
    return;
  }

  if (tip !== null && !(await isOurs(tip))) {
    warning(
      `${branch} has commits not made by this workflow; leaving it and its PR alone.`,
    );
    return;
  }
  // A PR with this exact update that someone closed without merging stays
  // closed until the update changes.
  if (pr === null) {
    const closed = (await pulls("closed")).filter(
      (p) => p.merged_at === null || p.merged_at === undefined,
    );
    if (closed.some((p) => (p.body ?? "").includes(built.marker))) {
      log("A closed PR already proposed this exact update; not reopening it.");
      return;
    }
  }

  const push = await pushUpdate(api, repo, meta, {
    branch,
    tip,
    paths,
    out: ctx.out,
    message: commitMessage(title, kind),
  });
  if (push === "moved") {
    warning(`${branch} moved while this run worked on it; leaving it alone.`);
    return;
  }
  if (push === "holds") {
    log(`${branch} already holds this update.`);
  } else {
    log(`Pushed ${push} to ${branch}.`);
  }
  const pushed = push !== "holds";

  let created = false;
  if (pr === null) {
    // The label is a convenience; a token that may not manage labels still
    // gets its PR.
    let labels: string[] = [LABEL];
    const spec = {
      color: "1d76db",
      description:
        "Opened by the maintenance-updates workflow (valuecodes/automation)",
    };
    try {
      try {
        await api("POST", `repos/${repo}/labels`, { name: LABEL, ...spec });
      } catch (error) {
        if (!(error instanceof HttpError && error.status === 422)) {
          throw error;
        }
        await api("PATCH", `repos/${repo}/labels/${LABEL}`, spec);
      }
    } catch {
      warning(
        "Could not create the maintenance-updates label; opening the PR without it.",
      );
      labels = [];
    }
    let opened: Pull;
    try {
      opened = await api<Pull>("POST", `repos/${repo}/pulls`, {
        title,
        head: branch,
        base: meta.base,
        body: built.body,
      });
    } catch (error) {
      if (error instanceof HttpError) {
        console.error(error.body);
        if (
          /not permitted to create or approve pull requests/i.test(error.body)
        ) {
          throw new Fail(
            `GitHub Actions may not open PRs in ${repo}. Turn on "Allow GitHub Actions to create and approve pull requests" under Settings → Actions → General (and in the organization's settings), then re-run.`,
          );
        }
        throw new Fail(`Could not open a PR for ${branch}.`);
      }
      throw error;
    }
    if (labels.length > 0) {
      await api("POST", `repos/${repo}/issues/${opened.number}/labels`, {
        labels,
      });
    }
    log(`Opened ${opened.html_url ?? `#${opened.number}`}.`);
    created = true;
  } else if (unchanged(pr, title, built)) {
    log(`PR #${pr.number} is unchanged.`);
  } else {
    await api("PATCH", `repos/${repo}/pulls/${pr.number}`, {
      title,
      body: built.body,
    });
    log(`Updated PR #${pr.number}.`);
  }

  if (ctx.ciWorkflow !== "" && (pushed || created)) {
    try {
      await api(
        "POST",
        `repos/${repo}/actions/workflows/${encodeURIComponent(ctx.ciWorkflow)}/dispatches`,
        { ref: branch },
      );
    } catch (error) {
      if (error instanceof HttpError) {
        console.error(error.body);
        throw new Fail(
          `Could not start ${ctx.ciWorkflow} on ${branch}. It needs an \`on: workflow_dispatch:\` trigger, and the caller job needs \`actions: write\`.`,
        );
      }
      throw error;
    }
    log(`Started ${ctx.ciWorkflow} on ${branch}.`);
  }
};

const pr = async (api: Api = githubApi): Promise<void> => {
  const ctx = updateContext();
  const outcome = readState(ctx.out);
  if (outcome === null) {
    throw new Fail(`The ${ctx.kind} step wrote no result.`);
  }
  await publish(api, ctx, readMeta(ctx.out), outcome);
};

export { label, commitMessage, body, unchanged, ours, publish, pr };
export type { Pull };
